#pragma once

#include "IOModule.h"


namespace base
{

template <   typename DI, int32_t cDigitalInputChannels
           , typename DO, int32_t cDigitalOutputChannels
           , typename AI, int32_t cAnalogInputChannels
           , typename AO, int32_t cAnalogOutputChannels>

class CIOBaseConfig
{
private:
    CIOModule<DI, cDigitalInputChannels> m_DI;
    CIOModule<DO, cDigitalOutputChannels> m_DO;
    CIOModule<AI, cAnalogInputChannels> m_AI;
    CIOModule<AO, cAnalogOutputChannels> m_AO;

public:
    CIOBaseConfig() = default;
    CIOBaseConfig(const CIOBaseConfig&) = default;
    CIOBaseConfig(CIOBaseConfig&& cfg) noexcept :
        m_DI{ std::move(cfg.m_DI) }
        , m_DO{ std::move(cfg.m_DO) }
        , m_AI{ std::move(cfg.m_AI) }
        , m_AO{ std::move(cfg.m_AO) }
    {}

    CIOBaseConfig& operator = (const CIOBaseConfig&) = default;

    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    CIOModule<DI, cDigitalInputChannels>& getDI()
    {     return m_DI;    }
    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    const CIOModule<DI, cDigitalInputChannels>& getDI() const
    {  return m_DI;    }
    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    CIOModule<DO, cDigitalOutputChannels>& getDO()
    {   return m_DO;   }
    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    const CIOModule<DO, cDigitalOutputChannels>& getDO() const
    {  return m_DO;   }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    CIOModule<AI, cAnalogInputChannels>& getAI()
    {   return m_AI;    }
    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    const CIOModule<AI, cAnalogInputChannels>& getAI() const
    {   return m_AI;    }
    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    CIOModule<AO, cAnalogOutputChannels>& getAO()
    {  return m_AO;    }
    //--------------------------------------------------------------------------------------------------------
    //--------------------------------------------------------------------------------------------------------
    const CIOModule<AO, cAnalogOutputChannels>& getAO() const
    {   return m_AO;    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------

    BOOL operator == (const CIOBaseConfig& cfg) const
    {
        return (m_DI == cfg.m_DI) && (m_DO == cfg.m_DO) &&
            (m_AI == cfg.m_AI) && (m_AO == cfg.m_AO);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    BOOL operator != (const CIOBaseConfig& cfg) const
    {
        return !operator == (cfg);
    }

    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    int32_t GetChannel(const DI type) const
    {
        return m_DI.Get(type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void GetType(const int32_t channel, DI& rType) const
    {
        rType = m_DI.Get(channel);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    int32_t GetChannel(const DO type) const
    {
        return m_DO.Get(type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void GetType(const int32_t channel, DO& rType) const
    {
        rType = m_DO.Get(channel);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    int32_t GetChannel(const AI type) const
    {
        return m_AI.Get(type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void GetType(const int32_t channel, AI& rType) const
    {
        rType = m_AI.Get(channel);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    int32_t GetChannel(const AO type) const
    {
        return m_AO.Get(type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void GetType(const int32_t channel, AO& rType) const
    {
        rType = m_AO.Get(channel);
    }
    //----------------------------------------------------------------------------------------------------
//----------------------------------------------------------------------------------------------------
    void Set(const int32_t channel, const DI type)
    {
        this->m_DI.Set(channel, type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void Set(const int32_t channel, const DO type)
    {
        this->m_DO.Set(channel, type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void Set(const int32_t channel, const AO type)
    {
        this->m_AO.Set(channel, type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    void Set(const int32_t channel, const AI type)
    {
        this->m_AI.Set(channel, type);
    }
    //----------------------------------------------------------------------------------------------------
    //----------------------------------------------------------------------------------------------------
    BOOL IsValidCount() const
    {
        return (m_DI.GetValidCount() + m_DO.GetValidCount() + m_AI.GetValidCount() + m_AO.GetValidCount()) > 0;
    }
};

};
