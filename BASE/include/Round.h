#pragma once

#include "BASE/types.h"

//***********************************************************************************************************
//***********************************************************************************************************
namespace base
{
namespace metric
{
//***********************************************************************************************************
//***********************************************************************************************************
inline int32_t nextlong(const float32_t value)
{   return _S32((value + 0.5F) - _F32(value < 0)); }
//***********************************************************************************************************
//***********************************************************************************************************
inline int32_t nextlong(const float64_t value)
{   return _S32((value + 0.5F) - _F32(value < 0)); }
//***********************************************************************************************************
//***********************************************************************************************************
template <int32_t D>
inline float32_t round(const float32_t value)
{	return _F32(nextlong(value * _F32(D))) / _F32(D); }
//***********************************************************************************************************
//***********************************************************************************************************
template <>
inline float32_t round<1>(const float32_t value)
{ return _F32(nextlong(value)); }

};
};

#define NEXTLONG(x) base::metric::nextlong(x)
#define ROUND0(x) base::metric::round<1>(x)
#define ROUND1(x) base::metric::round<10>(x)
#define ROUND2(x) base::metric::round<100>(x)
#define ROUND3(x) base::metric::round<1000>(x)
#define ROUND4(x) base::metric::round<10000>(x)


