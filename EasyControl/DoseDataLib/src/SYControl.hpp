int32_t CDose :: System_SetDosierItems	( const uint32_t s)
{
	std::lock_guard<std::mutex> lock(mSGlobal);
	auto& item = mSGlobal.get();
	item.sMaxItems = s;
	return DOSIERUNG_OK;
}

//+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
int32_t CDose :: System_GetDosierItems (uint32_t *s) const
{
	assert(s);
	*s = 0;

	const auto& item = mSGlobal.get();
	*s = item.sMaxItems;
	return DOSIERUNG_OK;
}


