int32_t  AdsClient_Open(const base::CIOConfig& rIOConfig)
{
    IAdsClientInterface::GetAdsClientInterface(&g_AdsClientInterface);
    return g_AdsClientInterface->Open(rIOConfig);
}
//*************************************************************************************************************
//*************************************************************************************************************
int32_t  AdsClient_Close(void)
{
    assert(g_AdsClientInterface);
    auto result = g_AdsClientInterface->Close();
    IAdsClientInterface::RemoveAdsClientInterface();
    return result;
}

